// Embeds python/speech_server.py into src/generated/speech-server-py.ts.
// The host bundle must be self-contained: the plugin directory is not
// available on remote machines, so the Python source ships as a string.
// Runs automatically before build, typecheck and test.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = join(root, "python", "speech_server.py");
const generatedPath = join(root, "src", "generated", "speech-server-py.ts");

const source = readFileSync(sourcePath, "utf8");
mkdirSync(dirname(generatedPath), { recursive: true });
writeFileSync(
  generatedPath,
  [
    "// Generated by scripts/embed-python.mjs from python/speech_server.py. Do not edit.",
    `export const SPEECH_SERVER_PY = ${JSON.stringify(source)};`,
    "",
  ].join("\n"),
);
console.log(`wrote ${generatedPath}`);
